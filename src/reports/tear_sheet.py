# ── Logo helper ───────────────────────────────────────────────────────────────

_ASSETS       = Path(__file__).resolve().parent.parent.parent / "assets"
_LOGO_PATH      = _ASSETS / "logo.png"       # full ALPHAFORGE wordmark
_LOGO_MARK_PATH = _ASSETS / "logo_mark.png"  # clean AF blade emblem


def _logo_b64_img(height: int = 44) -> str:
    """
    Embed logo as base64 <img> in the HTML tear sheet.
    Uses assets/logo.png or assets/logo_mark.png when present; falls back to ⚡.
    """
    for p in (_LOGO_PATH, _LOGO_MARK_PATH):
        if p.exists():
            b64 = base64.b64encode(p.read_bytes()).decode()
            return (
                f'<img src="data:image/png;base64,{b64}" height="{height}" '
                f'style="vertical-align:middle; border-radius:4px;" alt="AlphaForge">'
            )
    return '<span style="font-size:1.6rem; margin-right:8px;">⚡</span>'

