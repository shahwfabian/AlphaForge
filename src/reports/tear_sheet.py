# ── CSV export ────────────────────────────────────────────────────────────────

def generate_csv_report(metrics: dict, config: dict) -> str:
    """
    Generate a flat CSV string of all metrics and config values.

    Returns
    -------
    str
        CSV text suitable for st.download_button.
    """
    PCT_KEYS = {
        "Cumulative_Return", "CAGR", "Volatility_Ann", "Max_Drawdown",
        "Win_Rate", "VaR_95_Historical", "VaR_99_Historical",
        "ES_95_Historical", "ES_99_Historical", "Alpha_Ann",
        "Tracking_Error",
    }

    lines = ["Metric,Value"]

    # Config header
    for k in ("strategy", "ticker", "benchmark", "start_date", "end_date",
              "initial_capital", "transaction_cost", "slippage"):
        lines.append(f"{k},{config.get(k, '')}")

    lines.append("---,---")

    # Metrics
    for k, v in metrics.items():
        if isinstance(v, float) and np.isnan(v):
            val = "N/A"
        elif isinstance(v, float):
            val = f"{v*100:.4f}%" if k in PCT_KEYS else f"{v:.6f}"
        else:
            val = str(v)
        lines.append(f"{k},{val}")

    return "\n".join(lines)
